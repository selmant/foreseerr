/**
 * Writes server/lib/db/compileRegistry.ts with static TypeORM imports.
 * bun build --compile cannot load dist entity/migration globs from disk.
 */
import { globSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const TEST_FILE_PATTERN = /\.test\.[cm]?[jt]sx?$/;

const GLOBS = {
  entities: 'server/entity/**/*.ts',
  subscribers: 'server/subscriber/**/*.ts',
  sqlite: 'server/migration/sqlite/**/*.ts',
  postgres: 'server/migration/postgres/**/*.ts',
};

function toRepoPath(absolutePath) {
  return relative(REPO_ROOT, absolutePath).replaceAll('\\', '/');
}

function toServerImport(repoPath) {
  return `@server/${repoPath.slice('server/'.length).replace(/\.ts$/, '')}`;
}

function sourceFiles(pattern) {
  return globSync(pattern, { cwd: REPO_ROOT })
    .filter((file) => !TEST_FILE_PATTERN.test(file))
    .sort()
    .map((file) => join(REPO_ROOT, file));
}

function extractEntityBinding(source) {
  if (!/@Entity\b/.test(source)) {
    throw new Error('missing @Entity');
  }
  const entityIndex = source.search(/@Entity\s*(?:\([^)]*\))?/);
  const classMatch = source
    .slice(entityIndex)
    .match(/\b(?:export\s+)?class\s+(\w+)/);
  if (!classMatch) {
    throw new Error('missing class after @Entity');
  }
  const name = classMatch[1];
  if (new RegExp(`export\\s+class\\s+${name}\\b`).test(source)) {
    return { kind: 'named', name };
  }
  return { kind: 'default', name };
}

function extractExportedClass(source, label) {
  const match = source.match(/export class (\w+)/);
  if (!match) {
    throw new Error(`missing export class in ${label}`);
  }
  return match[1];
}

function aliasFor(prefix, filePath, className) {
  const stamp = basename(filePath, '.ts').replace(/[^a-zA-Z0-9]/g, '_');
  return `${prefix}_${stamp}_${className}`;
}

function collectEntities() {
  return sourceFiles(GLOBS.entities).map((filePath) => {
    const repoPath = toRepoPath(filePath);
    const binding = extractEntityBinding(readFileSync(filePath, 'utf8'));
    return {
      ...binding,
      importPath: toServerImport(repoPath),
      local: binding.name,
    };
  });
}

function collectNamedClasses(pattern, prefix) {
  return sourceFiles(pattern).map((filePath) => {
    const repoPath = toRepoPath(filePath);
    const className = extractExportedClass(
      readFileSync(filePath, 'utf8'),
      repoPath
    );
    return {
      importPath: toServerImport(repoPath),
      className,
      local: aliasFor(prefix, filePath, className),
    };
  });
}

function renderImport({ kind, local, importPath, className }) {
  if (kind === 'default') {
    return `import ${local} from '${importPath}';`;
  }
  if (kind === 'named') {
    return `import { ${local} } from '${importPath}';`;
  }
  return `import { ${className} as ${local} } from '${importPath}';`;
}

export function generateCompileRegistrySource() {
  const entities = collectEntities();
  const subscribers = collectNamedClasses(GLOBS.subscribers, 'sub');
  const sqlite = collectNamedClasses(GLOBS.sqlite, 'sqlite');
  const postgres = collectNamedClasses(GLOBS.postgres, 'pg');

  const imports = [
    ...entities.map(renderImport),
    ...subscribers.map(renderImport),
    ...sqlite.map(renderImport),
    ...postgres.map(renderImport),
  ].join('\n');

  const entityList = entities
    .map((item) => `  asEntity(${item.local}, '${item.local}'),`)
    .join('\n');

  const list = (items, key = 'local') =>
    items.map((item) => `  ${item[key]},`).join('\n');

  return `/* Generated by scripts/generate-compile-registry.mjs. Do not edit. */
${imports}

function asEntity<T extends { name: string }>(ctor: T, name: string): T {
  Object.defineProperty(ctor, 'name', { value: name, configurable: true });
  return ctor;
}

export const compileEntities = [
${entityList}
] as const;

export const compileSubscribers = [
${list(subscribers)}
] as const;

export const compileSqliteMigrations = [
${list(sqlite)}
] as const;

export const compilePostgresMigrations = [
${list(postgres)}
] as const;
`;
}

export function compileRegistryPath() {
  return `${REPO_ROOT}/server/lib/db/compileRegistry.ts`;
}

if (import.meta.main) {
  const source = generateCompileRegistrySource();
  writeFileSync(compileRegistryPath(), source);
  console.log(`wrote ${compileRegistryPath()}`);
}
