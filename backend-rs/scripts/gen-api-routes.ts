// Generate backend-rs/src/standalone/apiroutes.rs from seerr-api.yml: the
// routes express-openapi-validator knows, in the order it matches them, with
// the methods each one documents and whether the method needs a credential.
//
// Standalone mode uses the table to answer what the validator answers for
// requests no Rust handler takes: 405 for an undocumented method, 401 when a
// secured route has neither a session cookie nor an API key.
//
// The route list and its order follow the validator's OpenApiSpecLoader:
// `{param}` becomes `:param`, routes are sorted with its `sortRoutes`, and
// the first route registered for an Express path wins.
//
// Run from the repository (mise picks the bun the server uses there):
//   cd <repo> && bun <crate>/scripts/gen-api-routes.ts <repo> <crate>
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const [repo, crate] = process.argv.slice(2);
if (!repo || !crate) {
  throw new Error('usage: gen-api-routes.ts <repo> <crate>');
}
const require = createRequire(join(repo, 'package.json'));
const yaml = require('js-yaml') as { load(text: string): unknown };
const { sortRoutes } =
  require('express-openapi-validator/dist/framework/openapi.spec.loader') as {
    sortRoutes(
      a: { expressRoute: string },
      b: { expressRoute: string }
    ): number;
  };

type Operation = { security?: Record<string, unknown>[] };
type Doc = {
  security?: Record<string, unknown>[];
  paths: Record<string, Record<string, Operation>>;
};
const doc = yaml.load(readFileSync(join(repo, 'seerr-api.yml'), 'utf8')) as Doc;

const METHODS = [
  'get',
  'put',
  'post',
  'delete',
  'options',
  'head',
  'patch',
  'trace',
];
const BASE = '/api/v1';

const secured = (op: Operation): boolean => {
  const list = op.security ?? doc.security;
  if (!Array.isArray(list) || list.length === 0) return false;
  // An empty requirement object always passes.
  return !list.some((req) => Object.keys(req).length === 0);
};

type Route = {
  expressRoute: string;
  openApiRoute: string;
  methods: [string, boolean][];
};
const routes: {
  expressRoute: string;
  openApiRoute: string;
  method: string;
  secured: boolean;
}[] = [];
for (const [path, item] of Object.entries(doc.paths)) {
  if (/[*:()]/.test(path)) {
    throw new Error(`unsupported path syntax: ${path}`);
  }
  for (const [method, op] of Object.entries(item)) {
    if (
      method.startsWith('x-') ||
      ['parameters', 'summary', 'description'].includes(method)
    ) {
      continue;
    }
    if (!METHODS.includes(method))
      throw new Error(`unknown method ${method} on ${path}`);
    const openApiRoute = `${BASE}${path}`;
    routes.push({
      expressRoute: openApiRoute.replace(/\{([^/}]+)}/g, ':$1'),
      openApiRoute,
      method: method.toUpperCase(),
      secured: secured(op),
    });
  }
}
routes.sort(sortRoutes);

// expressRouteMap: one entry per Express path, in first-seen order; its
// methods are every method documented under the OpenAPI path.
const byExpress = new Map<string, Route>();
for (const r of routes) {
  if (!byExpress.has(r.expressRoute)) {
    const item = doc.paths[r.openApiRoute.slice(BASE.length)];
    const methods: [string, boolean][] = Object.entries(item)
      .filter(([m]) => METHODS.includes(m))
      .map(([m, op]) => [m.toUpperCase(), secured(op)]);
    byExpress.set(r.expressRoute, {
      expressRoute: r.expressRoute,
      openApiRoute: r.openApiRoute,
      methods,
    });
  }
}

const lit = (s: string) => JSON.stringify(s);
const lines = [...byExpress.values()].map((r) => {
  const segments = r.expressRoute
    .slice(1)
    .split('/')
    .map((s) => (s.startsWith(':') ? 'None' : `Some(${lit(s)})`))
    .join(', ');
  const methods = r.methods.map(([m, s]) => `(${lit(m)}, ${s})`).join(', ');
  return `    ApiRoute {\n        template: ${lit(r.openApiRoute)},\n        segments: &[${segments}],\n        methods: &[${methods}],\n    },`;
});

const out = `//! Generated by \`scripts/gen-api-routes.ts\` from \`seerr-api.yml\`; do not
//! edit. The \`OpenAPI\` validator's routes in the order it matches them.

use super::fallback::ApiRoute;

/// Every documented route.
pub(super) static ROUTES: [ApiRoute; ${lines.length}] = [
${lines.join('\n')}
];
`;
writeFileSync(join(crate, 'src/standalone/apiroutes.rs'), out);
console.log(`wrote ${lines.length} routes`);
