// Generate backend-rs/src/dbmigrate/synchronize.rs and
// synchronize_reference.json: what TypeORM's `synchronize` does to a fresh
// SQLite database in development (server/datasource.ts `devConfig`).
//
// The entities are loaded exactly as the dev server loads them
// (`sourceEntityFiles()`), `dataSource.synchronize()` runs on an empty
// temporary file with a logger that records every statement, and the DDL
// between its BEGIN TRANSACTION and COMMIT is kept in order. The resulting
// sqlite_master is the reference the Rust test compares against.
//
// Run from the repository (mise picks the bun the server uses there):
//   cd <repo> && bun <crate>/scripts/gen-synchronize.ts <repo> <crate>
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const [repo, crate] = process.argv.slice(2);
if (!repo || !crate) {
  throw new Error('usage: gen-synchronize.ts <repo> <crate>');
}
const requireFromRepo = createRequire(join(repo, 'package.json'));
const { DataSource } = requireFromRepo('typeorm');
const { bunSqlite3 } = await import(join(repo, 'server/lib/bunSqlite3.ts'));
// The entity classes register in the order the server's import graph
// evaluates them, and that order is the order of the DDL (and of the
// sqlite_sequence rows the table rebuilds leave). Load the graph first.
await import(join(repo, 'server/index.ts'));
const { sourceEntityFiles } = await import(
  join(repo, 'server/utils/typeormGlobs.ts')
);

const recorded: { query: string; parameters?: unknown[] }[] = [];
const logger = {
  logQuery: (query: string, parameters?: unknown[]) =>
    recorded.push({ query, parameters }),
  logQueryError: (error: unknown, query: string) => {
    throw new Error(`synchronize failed on ${query}: ${String(error)}`);
  },
  logQuerySlow: () => undefined,
  logSchemaBuild: () => undefined,
  logMigration: () => undefined,
  log: () => undefined,
};

const dir = mkdtempSync(join(tmpdir(), 'gen-synchronize-'));
const cwd = process.cwd();
process.chdir(repo);
const ds = new DataSource({
  type: 'sqlite',
  driver: bunSqlite3,
  database: join(dir, 'db.sqlite3'),
  synchronize: false,
  migrationsRun: false,
  enableWAL: true,
  logging: true,
  logger,
  entities: sourceEntityFiles(),
});
await ds.initialize();
recorded.length = 0;
await ds.synchronize();
const begin = recorded.findIndex((r) => r.query === 'BEGIN TRANSACTION');
const commit = recorded.findIndex((r) => r.query === 'COMMIT');
if (begin < 0 || commit < begin) {
  throw new Error('no synchronize transaction recorded');
}
// The reads (sqlite_master lookups for the table rebuilds) are left out:
// on an empty database they always find what the DDL before them made.
const statements = recorded
  .slice(begin + 1, commit)
  .filter((s) => !/^\s*SELECT\b/i.test(s.query));
for (const s of statements) {
  if (Array.isArray(s.parameters) && s.parameters.length > 0) {
    throw new Error(`parameters are not supported: ${s.query}`);
  }
}
const schema = await ds.query(
  `SELECT "type", "name", "tbl_name", "sql" FROM sqlite_master WHERE "name" NOT LIKE 'sqlite_%' ORDER BY "type", "name"`
);
await ds.destroy();
process.chdir(cwd);
rmSync(dir, { recursive: true, force: true });

function rustString(s: string): string {
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

const out = join(crate, 'src/dbmigrate');
writeFileSync(
  join(out, 'synchronize.rs'),
  [
    "//! The DDL `TypeORM`'s `synchronize` sends to a fresh `SQLite` database",
    '//! for the entities in `server/entity`, in order (between its',
    '//! `BEGIN TRANSACTION` and `COMMIT`).',
    '//! Generated by `scripts/gen-synchronize.ts`; do not edit.',
    '',
    '/// Every statement, in order.',
    'pub(super) const STATEMENTS: &[&str] = &[',
    ...statements.map((s) => `    ${rustString(s.query)},`),
    '];',
    '',
  ].join('\n')
);
writeFileSync(
  join(out, 'synchronize_reference.json'),
  JSON.stringify({ schema }, undefined, 1) + '\n'
);
console.log(`${statements.length} statements, ${schema.length} schema rows`);
process.exit(0);
